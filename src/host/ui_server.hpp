// Built-in web UI: a small HTTP server that serves the single-page board view
// (embedded in the executable) and bridges it to the emulation thread.
//
//   GET  /                 the UI (index.html), other embedded assets by path
//   GET  /api/catalog      chip families and boards (JSON, set by main)
//   GET  /events           Server-Sent Events: "state" (JSON) and "serial" (base64)
//   POST /api/<command>    JSON body, queued for the emulation thread
//
// The HTTP threads never touch the chip: commands go through a queue that the
// main loop drains, and the main loop publishes state snapshots.
#pragma once
#include <atomic>
#include <condition_variable>
#include <cstdint>
#include <deque>
#include <memory>
#include <mutex>
#include <string>
#include <thread>
#include <vector>

#include "util/json.hpp"

namespace esp32sim {

struct UiAsset {
    const char* path;  // "index.html", "layouts/<board>.json", "images/<file>"
    const unsigned char* data;
    size_t size;
};
// Assets compiled into the executable (generated by tools/embed_assets.cmake).
const UiAsset* find_ui_asset(const std::string& path);

struct UiCommand {
    std::string name;  // "board", "pin", "reset", "serial", ...
    Json args;
};

class UiServer {
public:
    UiServer(std::string bind, int port);
    ~UiServer();

    bool start(std::string* error);
    void stop();
    std::string url() const;

    void set_catalog(std::string json);
    void publish_state(std::string json);
    void publish_serial(const uint8_t* data, size_t len);
    bool poll(UiCommand& cmd);

private:
    struct Request {
        std::string method, path, body;
    };
    void accept_loop();
    void handle(intptr_t sock);
    void serve_events(intptr_t sock);

    std::string bind_;
    int port_;
    intptr_t listen_ = -1;
    std::atomic<bool> running_{false};
    std::atomic<int> connections_{0};
    std::thread thread_;

    std::mutex m_;
    std::condition_variable cv_;
    std::string catalog_ = "{}";
    std::string state_ = "{}";
    uint64_t state_version_ = 0;
    std::string serial_;         // recent serial output
    uint64_t serial_base_ = 0;   // stream offset of serial_[0]
    std::deque<UiCommand> commands_;
};

}  // namespace esp32sim
